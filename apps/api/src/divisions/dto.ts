import { IsBoolean, IsInt, IsOptional, IsString, Min } from "class-validator";

export class CreateDivisionDto {
  @IsString() slug!: string;
  @IsString() name!: string;
  @IsOptional() @IsString() description?: string;
}

export class CreateAgentRoleDto {
  @IsString() name!: string;
  @IsString() tier!: "ATAS" | "AHLI" | "RUTIN";
  @IsOptional() @IsString() responsibilities?: string;
  @IsOptional() @IsInt() @Min(1) maxConcurrentTasks?: number;
  @IsOptional() @IsBoolean() requiresApproval?: boolean;
}

/**
 * "Perannya saya yang buat, untuk Nama dan Model itu generate dari agentic
 * AI" - the director only supplies the role name (and, optionally, what it
 * does); the tier is inferred from that text via inferRoleCapability, and
 * the new agent's display name is generated by asking the model itself.
 * Deliberately no `tier` field here - that's the whole point of this DTO.
 */
export class QuickAddPersonnelDto {
  @IsString() roleName!: string;
  @IsOptional() @IsString() responsibilities?: string;
}
